// Signatures.h - what is supposed to be at every address this plugin uses.
//
// Only the addresses Going Catch You really touches. The bytes were read out of
// TESV.exe 1.9.32.0.8 by the generator of the FreeRun NPC project and copied
// here unchanged. When a later step starts using a new address, its line is
// added here too, so Verify.cpp checks it before anything is hooked.
//
// See Verify.cpp for what is done with it.

#pragma once

#include "skse/skse_version.h"

namespace Signatures
{
	enum Kind
	{
		kCode,       // a function: the bytes are fixed and must match
		kTable,      // a vtable: fixed too, but another plugin may hook it first
		kVariable,   // written by the game at runtime: only the address is checked
	};

	struct Site
	{
		unsigned long	address;
		const char *	name;
		const char *	where;
		Kind			kind;
		unsigned char	bytes[24];
		unsigned char	length;
	};

	static const Site kSites[] =
	{
		{ 0x004A9180, "LookupREFRByHandle", "Engine.cpp", kCode, { 0x53, 0x55, 0x8B, 0x6C, 0x24, 0x0C, 0x8B, 0x45, 0x00, 0x56, 0x57, 0x85, 0xC0, 0x0F, 0x84, 0x8C, 0x00, 0x00, 0x00, 0x8B, 0xF0, 0x25, 0x00, 0x00 }, 24 },
		{ 0x01310588, "Engine", "Engine.h", kVariable, { 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 }, 0 },
		{ 0x010E29EC, "kThirdPersonState", "Tick.cpp", kTable, { 0x30, 0x8D, 0x83, 0x00, 0x70, 0xFB, 0x83, 0x00, 0x60, 0xFC, 0x83, 0x00, 0x20, 0x09, 0x84, 0x00, 0xB0, 0xF4, 0x83, 0x00, 0x60, 0xF8, 0x83, 0x00 }, 24 },
		{ 0x010E30C8, "kFirstPersonState", "Tick.cpp", kTable, { 0x70, 0xC0, 0x83, 0x00, 0xB0, 0x99, 0x83, 0x00, 0xF0, 0x99, 0x83, 0x00, 0x40, 0xA2, 0x83, 0x00, 0x60, 0x9F, 0x83, 0x00, 0x30, 0x99, 0x83, 0x00 }, 24 },
	};

	enum { kSiteCount = sizeof(kSites) / sizeof(kSites[0]) };
}
